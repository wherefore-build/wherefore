#!/usr/bin/env python3
"""README.md, from docs/README.template.md and the commands.

The README's prose is the template's, written by a person. Its list of
commands is not: it is src/wherefore/commands.json, the one place the commands
are said, which `wherefore --help` prints too. So a command added, renamed or
re-described changes the README by being regenerated, never by being retyped -
and the gate fails a README edited by hand, because it is not what this makes.

Run from corpus/, as wherefore.json says. Reads two files, writes one.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "docs/README.template.md"
COMMANDS = ROOT / "src/wherefore/commands.json"
OUT = ROOT / "README.md"

HEADER = ("<!-- Generated by corpus/readme.py from docs/README.template.md and "
          "src/wherefore/commands.json. Edit those, not this. -->\n")


def listing(rows):
    width = max(len(c["usage"]) for c in rows) + 2
    return "\n".join(f"{c['usage']:<{width}}# {c['does']}" for c in rows)


def main():
    rows = json.loads(COMMANDS.read_text(encoding="utf-8"))["commands"]
    template = TEMPLATE.read_text(encoding="utf-8")
    if template.count("{{commands}}") != 1:
        raise SystemExit(f"{TEMPLATE.relative_to(ROOT)} must hold {{{{commands}}}} exactly once")
    OUT.write_text(HEADER + template.replace("{{commands}}", listing(rows)), encoding="utf-8")


if __name__ == "__main__":
    main()
