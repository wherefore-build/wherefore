#!/usr/bin/env python3
"""README.md, from docs/README.template.md, the commands and the principles.

The README's prose is the template's, written by a person. Its list of
commands is not: it is src/wherefore/commands.json, the one place the commands
are said, which `wherefore --help` prints too. Nor are its principles: they are
src/wherefore/principles.json, which the company's site reads as well. So a
command or a principle added, renamed or re-worded changes the README by being
regenerated, never by being retyped - and the gate fails a README edited by
hand, because it is not what this makes.

Run from corpus/, as wherefore.json says. Reads three files, writes one.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "docs/README.template.md"
COMMANDS = ROOT / "src/wherefore/commands.json"
PRINCIPLES = ROOT / "src/wherefore/principles.json"
OUT = ROOT / "README.md"

HEADER = ("<!-- Generated by corpus/readme.py from docs/README.template.md, "
          "src/wherefore/commands.json and src/wherefore/principles.json. "
          "Edit those, not this. -->\n")


def listing(rows):
    width = max(len(c["usage"]) for c in rows) + 2
    return "\n".join(f"{c['usage']:<{width}}# {c['does']}" for c in rows)


def numbered(rows):
    return "\n".join(f"{n}. **{p['rule']}**" + (f" {p['says']}" if p["says"] else "")
                     for n, p in enumerate(rows, 1))


def main():
    commands = json.loads(COMMANDS.read_text(encoding="utf-8"))["commands"]
    principles = json.loads(PRINCIPLES.read_text(encoding="utf-8"))["principles"]
    text = TEMPLATE.read_text(encoding="utf-8")
    for slot, filled in (("{{commands}}", listing(commands)), ("{{principles}}", numbered(principles))):
        if text.count(slot) != 1:
            raise SystemExit(f"{TEMPLATE.relative_to(ROOT)} must hold {slot} exactly once")
        text = text.replace(slot, filled)
    OUT.write_text(HEADER + text, encoding="utf-8")


if __name__ == "__main__":
    main()
