"""`wherefore graph`: what builds what, from a real run, that changes nothing.

Every case runs the command on a committed copy of the fixture company, and
holds what it says to the gate's own classification and to the tree as it was.
"""
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

from _util import ENGINE, git, wherefore

FIXTURE = ENGINE / "tests" / "fixture"
RESAVE = ["sh", "-c", "cp ../deck/one-pager.svg ../deck/.again && cat ../deck/.again > ../deck/one-pager.svg "
                      "&& rm ../deck/.again"]


def fernhollow(edit=None):
    """A committed copy of the fixture, after `edit(wherefore.json as a dict)`."""
    root = pathlib.Path(tempfile.mkdtemp(prefix="wherefore-graph-")) / "fernhollow"
    shutil.copytree(FIXTURE, root, ignore=shutil.ignore_patterns("__pycache__"))
    if edit:
        p = root / "wherefore.json"
        d = json.loads(p.read_text(encoding="utf-8"))
        edit(d)
        p.write_text(json.dumps(d, indent=1) + "\n", encoding="utf-8")
    git(root, "init", "-q")
    git(root, "add", "-A")
    git(root, "-c", "user.email=t@wherefore", "-c", "user.name=t", "commit", "-qm", "x")
    return root


def graph(root, *extra):
    out = root.parent / "out"
    out.mkdir(exist_ok=True)
    code, said = wherefore(root, "graph", "--html", str(out / "graph.html"),
                           "--json", str(out / "graph.json"), *extra)
    page = (out / "graph.html").read_text(encoding="utf-8") if (out / "graph.html").exists() else None
    data = json.loads((out / "graph.json").read_text(encoding="utf-8")) if (out / "graph.json").exists() else None
    return code, said, data, page


def with_resave(d):
    """A second writer: a command that saves the deck again, after deck.py."""
    d["generators"].insert(2, {"run": RESAVE, "cwd": "gen", "makes": "the deck, saved again"})


class TheGraphIsTheGatesClassification(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root = fernhollow()
        cls.code, cls.said, cls.data, cls.page = graph(cls.root)

    def test_it_passes_and_says_so_in_one_line(self):
        self.assertEqual(self.code, 0, self.said)
        self.assertIn("15 files: 4 generated by 4 scripts, 10 written by hand, 1 captured; "
                      "6 reads traced; wrote ", self.said)

    def test_the_counts_are_the_gates(self):
        code, out = wherefore(self.root, "gate")
        self.assertEqual(code, 0, out)
        gate = {k: int(re.search(rf"^\s+{k}\s+(\d+)", out, re.M).group(1))
                for k in ("generated", "authored", "captured", "UNKNOWN")}
        c = self.data["counts"]
        self.assertEqual((c["generated"], c["authored"], c["captured"], c["unknown"]),
                         (gate["generated"], gate["authored"], gate["captured"], gate["UNKNOWN"]))
        self.assertEqual(c["files"], int(re.search(r"(\d+) tracked files", out).group(1)))

    def test_a_source_read_by_a_generator_is_an_edge(self):
        landing = next(g for g in self.data["generators"] if g["name"] == "landing.py")
        self.assertIn("facts.json", landing["reads"])
        self.assertIn("gen/landing.py", landing["code"])
        self.assertNotIn("gen/landing.py", landing["reads"], "code is said apart from sources")
        self.assertEqual(landing["writes"], ["site/index.html"])
        self.assertNotIn("site/index.html", landing["reads"], "its own output is not a read")

    def test_the_json_says_its_schema(self):
        d = self.data
        self.assertEqual(d["schema"], 1)
        self.assertEqual(set(d), {"schema", "engine", "repository", "counts", "generators",
                                  "files", "captured", "authored"})
        import wherefore
        self.assertEqual(d["engine"], wherefore.__version__)
        self.assertEqual(d["repository"], "fernhollow-kettles")
        for g in d["generators"]:
            self.assertEqual(set(g), {"name", "cwd", "makes", "kind", "reads", "code", "writes",
                                      "rewrites", "failure"})
        self.assertEqual(d["files"]["site/index.html"], {"kind": "generated", "by": "landing.py", "also": []})
        self.assertEqual(d["files"]["facts.json"], {"kind": "authored", "rule": "facts.json"})
        self.assertEqual(d["files"]["photos/hero.svg"]["kind"], "captured")
        self.assertTrue(all({"rule", "why", "files"} <= set(r) for r in d["authored"]))
        self.assertTrue(all({"name", "why", "files", "stamp", "no_stamp", "upstream"} <= set(c)
                            for c in d["captured"]))

    def test_the_page_loads_nothing_from_anywhere_else(self):
        p = self.page
        self.assertFalse(re.search(r"""<(script|img|iframe|source|video|audio)\b[^>]*\bsrc\s*=""", p, re.I))
        self.assertNotRegex(p, r"(?i)<link\b")
        self.assertNotRegex(p, r"(?i)@import|url\(\s*['\"]?(https?:)?//")
        self.assertIn("prefers-color-scheme: dark", p)
        self.assertIn('"repository": "fernhollow-kettles"', p)


class TheMapCreditsItself(unittest.TestCase):
    """A corpus that publishes its own map: a `run` generator that is `wherefore graph`."""
    @classmethod
    def setUpClass(cls):
        def with_map(d):
            d["generators"].append({"run": [sys.executable, "-m", "wherefore", "graph", "--html", "map/index.html"],
                                    "cwd": ".", "makes": "map/index.html, the map of this corpus"})
        cls.root = fernhollow(with_map)
        (cls.root / "map").mkdir()
        (cls.root / "map/index.html").write_text("not the map yet\n", encoding="utf-8")
        git(cls.root, "add", "-A")
        git(cls.root, "-c", "user.email=t@wherefore", "-c", "user.name=t", "commit", "-qm", "a map, committed")
        cls.code, cls.said, cls.data, cls.page = graph(cls.root)
        cls.left = (cls.root / "map/index.html").read_text(encoding="utf-8")

    def test_the_graph_credits_it_and_does_not_run_it(self):
        self.assertEqual(self.code, 0, self.said)
        self.assertIn("16 files: 5 generated by 5 scripts, 10 written by hand, 1 captured; 6 reads traced; wrote ",
                      self.said)
        f = self.data["files"]["map/index.html"]
        self.assertEqual(f["kind"], "generated")
        self.assertTrue(f["by"].endswith("-m wherefore graph --html map/index.html"), f["by"])
        g = next(g for g in self.data["generators"] if g["name"] == f["by"])
        self.assertEqual((g["kind"], g["writes"], g["reads"], g["failure"]), ("run", ["map/index.html"], None, None))
        self.assertEqual(self.left, "not the map yet\n", "credited, not run: the file is as it was committed")

    def test_the_gate_runs_it_and_the_map_holds(self):
        code, out = wherefore(self.root, "build")
        self.assertNotEqual(code, 0, "the committed placeholder is not what the generator writes")
        page = (self.root / "map/index.html").read_text(encoding="utf-8")
        self.assertIn("fernhollow-kettles", page)
        self.assertIn("map/index.html", page, "the map names its own file")
        git(self.root, "add", "-A")
        git(self.root, "-c", "user.email=t@wherefore", "-c", "user.name=t", "commit", "-qm", "the map, as the generator writes it")
        code, out = wherefore(self.root, "gate")
        self.assertEqual(code, 0, out)
        self.assertIn("5 generated files, 0 differ from what is committed", out)
        self.assertIn("a second regeneration moves 0 files", out)


class TheMapInTheCorpussOwnColours(unittest.TestCase):
    """`--theme` puts a corpus's stylesheet where the page's own palettes were."""
    def test_the_theme_replaces_both_palettes(self):
        root = fernhollow()
        theme = root / "theme.css"
        theme.write_text(":root { --ground: var(--paper); --surface: var(--paper); --line: var(--rule); --ink: var(--text);\n"
                         "  --muted: var(--text); --accent: var(--go); --accent-ink: var(--paper); --lit: var(--paper);\n"
                         "  --gen: var(--go); --capt: var(--go); --hand: var(--text); --unk: var(--stop); --bad: var(--stop);\n"
                         "  --sans: Fern, sans-serif; --serif: Fern, serif; --mono: Fern, monospace; --r: 4px; }\n",
                         encoding="utf-8")
        code, said, data, page = graph(root, "--theme", str(theme))
        self.assertEqual(code, 0, said)
        self.assertIn("--ground: var(--paper)", page)
        for own in ("#F7F6F2", "#0B0C0E", "#3F6B00", "#C3FF0F", "prefers-color-scheme: dark"):
            self.assertNotIn(own, page, f"the page still carries its own palette: {own}")
        self.assertIn("background: var(--ground)", page, "the rules still read the properties the theme sets")

    def test_a_theme_that_is_not_there_is_refused_in_words(self):
        root = fernhollow()
        code, said, data, page = graph(root, "--theme", "no-such.css")
        self.assertEqual(code, 2)
        self.assertIn("--theme no-such.css: no such stylesheet", said)

    def test_a_map_generator_with_a_theme_is_still_credited_not_run(self):
        from wherefore import graph as G
        from wherefore.generators import Gen
        g = Gen(script=None, cwd=".", makes="", stdout_to=None, probe=None, resettle=False,
                run=[sys.executable, "-m", "wherefore", "graph", "--html", "site/map/index.html", "--theme", "site/brand/map.css"])
        self.assertEqual(G.maps_itself(g), ["site/map/index.html"])


class ItChangesNothing(unittest.TestCase):
    def test_the_tree_is_as_it_was(self):
        root = fernhollow()
        # Something worth putting back: a fact moved, so every generator would
        # write something new, and a page edited by hand.
        facts = root / "facts.json"
        facts.write_text(facts.read_text(encoding="utf-8").replace('"1.5"', '"1.6"').replace("1.5", "1.6"),
                         encoding="utf-8")
        (root / "site/index.html").write_text("<p>by hand</p>\n", encoding="utf-8")
        files = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True,
                               text=True).stdout.split("\0")
        before = {f: (root / f).read_bytes() for f in files if f}
        status = git(root, "status", "--porcelain", "--ignored").stdout
        code, said, _data, _page = graph(root)
        self.assertEqual(code, 0, said)
        self.assertEqual({f: (root / f).read_bytes() for f in before}, before)
        self.assertEqual(git(root, "status", "--porcelain", "--ignored").stdout, status)


class WhoMadeIt(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.code, cls.said, cls.data, cls.page = graph(fernhollow(with_resave))

    def test_the_first_writer_is_credited_and_the_second_is_also(self):
        self.assertEqual(self.code, 0, self.said)
        name = " ".join(__import__("shlex").quote(w) for w in RESAVE)
        self.assertEqual(self.data["files"]["deck/one-pager.svg"],
                         {"kind": "generated", "by": "deck.py", "also": [name]})
        resave = next(g for g in self.data["generators"] if g["kind"] == "run")
        self.assertEqual(resave["writes"], [])
        self.assertEqual(resave["rewrites"], ["deck/one-pager.svg"])

    def test_a_command_says_its_reads_were_not_observed(self):
        resave = next(g for g in self.data["generators"] if g["kind"] == "run")
        self.assertIsNone(resave["reads"])
        self.assertIsNone(resave["code"])
        self.assertIn("reads not observed", self.page)


class AFailureIsShownNotHidden(unittest.TestCase):
    def test_a_failing_generator_exits_one_and_the_page_still_says_so(self):
        def fail(d):
            d["generators"].append({"run": ["sh", "-c", "echo 'the kiln is cold' >&2; exit 5"],
                                    "cwd": "gen", "makes": "nothing today"})
        code, said, data, page = graph(fernhollow(fail))
        self.assertEqual(code, 1, said)
        self.assertIn("the kiln is cold", said)
        self.assertIn("1 generator FAILED", said)
        bad = [g for g in data["generators"] if g["failure"]]
        self.assertEqual(len(bad), 1)
        self.assertIn("the kiln is cold", bad[0]["failure"])
        self.assertIn("the kiln is cold", page)


class AClientThatConfiguresTheEngineInItsOwnScripts(unittest.TestCase):
    """The pendulum's shape: wherefore.json hands `list` and `gate` to scripts
    of its own, which configure the engine where its proofs plant faults."""

    def test_the_graph_reads_the_corpus_through_those_scripts(self):
        from _util import repo
        gens = ("import pathlib, sys\n"
                "from wherefore import generators as G\n"
                "ROOT = pathlib.Path(__file__).resolve().parents[1]\n"
                "G.configure(ROOT, [G.Gen('page.py', 'gen', 'site/page.html, the page')])\n"
                "if __name__ == '__main__':\n    sys.exit(G.main())\n")
        gate = ("import json, pathlib, sys\n"
                "import generators\n"
                "from wherefore import gate\n"
                "ROOT = pathlib.Path(__file__).resolve().parents[1]\n"
                "INV = ROOT / 'checks/inventory.json'\n"
                "gate.configure(ROOT, lambda: json.loads(INV.read_text()), None, 'checks/inventory.json',\n"
                "               None, None, gate.COMPARE)\n"
                "if __name__ == '__main__':\n    sys.exit(gate.main())\n")
        page = ("import pathlib\n"
                "ROOT = pathlib.Path(__file__).resolve().parents[1]\n"
                "n = (ROOT / 'facts.txt').read_text().strip()\n"
                "(ROOT / 'site').mkdir(exist_ok=True)\n"
                "(ROOT / 'site/page.html').write_text(f'<p>{n} days</p>\\n')\n")
        inv = {"authored": {"rules": [["*.py", "code"], ["wherefore.json", "the corpus"],
                                      ["checks/inventory.json", "the inventory"], ["facts.txt", "THE SOURCE"],
                                      [".gitignore", "bytecode"]]},
               "captured": {"groups": {}}}
        root = repo({"wherefore.json": {"wherefore": 1, "name": "pendulum-shaped", "entry": {
                         "why": "its lists live in the scripts its proofs plant into",
                         "list": "checks/generators.py", "gate": "checks/coverage_gate.py"}},
                     "checks/generators.py": gens, "checks/coverage_gate.py": gate,
                     "checks/inventory.json": inv, "gen/page.py": page, "facts.txt": "14\n",
                     "site/page.html": "<p>14 days</p>\n", ".gitignore": "__pycache__/\n"})
        code, out = wherefore(root, "gate")
        self.assertEqual(code, 0, out)
        code, said, data, _page = graph(root)
        self.assertEqual(code, 0, said)
        self.assertEqual(data["files"]["site/page.html"], {"kind": "generated", "by": "page.py", "also": []})
        self.assertEqual(data["generators"][0]["reads"], ["facts.txt"])
        self.assertEqual(data["counts"]["generated"], 1)
        self.assertEqual((data["counts"]["files"], data["counts"]["unknown"]), (8, 0))
        self.assertEqual(git(root, "status", "--porcelain").stdout, "")


class TheLine(unittest.TestCase):
    def test_flags_it_does_not_take_are_refused(self):
        root = fernhollow()
        self.assertEqual(wherefore(root, "graph", "--pdf", "x")[0], 2)
        self.assertEqual(wherefore(root, "graph", "--html")[0], 2)
        self.assertEqual(wherefore(root, "graph", "--html", "-", "--json", "-")[0], 2)

    def test_json_to_stdout_puts_the_summary_on_stderr(self):
        import os, sys
        from _util import SRC
        root = fernhollow()
        env = dict(os.environ, PYTHONPATH=str(SRC), WHEREFORE_ROOT=str(root))
        r = subprocess.run([sys.executable, "-m", "wherefore", "graph", "--html", str(root.parent / "g.html"),
                            "--json", "-"], cwd=root, env=env, capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(json.loads(r.stdout)["schema"], 1)
        self.assertIn("15 files:", r.stderr)


